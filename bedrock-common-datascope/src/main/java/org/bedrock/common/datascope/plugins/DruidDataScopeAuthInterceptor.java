
package org.bedrock.common.datascope.plugins;

import com.alibaba.druid.filter.FilterChain;
import com.alibaba.druid.filter.FilterEventAdapter;
import com.alibaba.druid.proxy.jdbc.ConnectionProxy;
import com.alibaba.druid.proxy.jdbc.PreparedStatementProxy;
import com.alibaba.druid.proxy.jdbc.StatementProxy;
import lombok.extern.slf4j.Slf4j;
import org.bedrock.common.auth.entity.AuthUser;
import org.bedrock.common.auth.util.AuthUtil;
import org.bedrock.common.datascope.handler.DataScopeAuthHolder;
import org.bedrock.common.datascope.model.DataScopeModel;
import org.bedrock.common.datascope.props.DataScopeProperties;
import org.bedrock.common.datascope.support.DataPermissionSqlProcessor;
import org.bedrock.common.code.util.SpringUtil;
import org.bedrock.common.code.util.StringUtil;

import java.sql.SQLException;
import java.util.regex.Pattern;

/**
 * druid 数据权限拦截器
 */
@Slf4j
public class DruidDataScopeAuthInterceptor extends FilterEventAdapter {

	/**
	 * 判断是否是查询语句
	 */
	private static final Pattern SELECT_PATTERN = Pattern.compile("^(?i)(\\s*)(select)(\\s+)((.)+)$");

	private static DataPermissionSqlProcessor sqlProcessor;

	private final DataScopeProperties dataScopeProperties;

	public DruidDataScopeAuthInterceptor(DataScopeProperties dataScopeProperties) {
		this.dataScopeProperties = dataScopeProperties;
	}

	@Override
	public boolean statement_execute(FilterChain chain, StatementProxy statement, String sql) throws SQLException {
		return super.statement_execute(chain, statement, sqlCondition(sql));
	}

	@Override
	public boolean statement_execute(FilterChain chain, StatementProxy statement, String sql, int autoGeneratedKeys) throws SQLException {
		return super.statement_execute(chain, statement, sqlCondition(sql), autoGeneratedKeys);
	}

	@Override
	public boolean statement_execute(FilterChain chain, StatementProxy statement, String sql, int[] columnIndexes) throws SQLException {
		return super.statement_execute(chain, statement, sqlCondition(sql), columnIndexes);
	}

	@Override
	public boolean statement_execute(FilterChain chain, StatementProxy statement, String sql, String[] columnNames) throws SQLException {
		return super.statement_execute(chain, statement, sqlCondition(sql), columnNames);
	}

	@Override
	public PreparedStatementProxy connection_prepareStatement(FilterChain chain, ConnectionProxy connection, String sql) throws SQLException {
		return super.connection_prepareStatement(chain, connection, sqlCondition(sql));
	}

	@Override
	public PreparedStatementProxy connection_prepareStatement(FilterChain chain, ConnectionProxy connection, String sql, int autoGeneratedKeys) throws SQLException {
		return super.connection_prepareStatement(chain, connection, sqlCondition(sql), autoGeneratedKeys);
	}

	@Override
	public PreparedStatementProxy connection_prepareStatement(FilterChain chain, ConnectionProxy connection, String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		return super.connection_prepareStatement(chain, connection, sqlCondition(sql), resultSetType, resultSetConcurrency);
	}

	@Override
	public PreparedStatementProxy connection_prepareStatement(FilterChain chain, ConnectionProxy connection, String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		return super.connection_prepareStatement(chain, connection, sqlCondition(sql), resultSetType, resultSetConcurrency, resultSetHoldability);
	}

	@Override
	public PreparedStatementProxy connection_prepareStatement(FilterChain chain, ConnectionProxy connection, String sql, int[] columnIndexes) throws SQLException {
		return super.connection_prepareStatement(chain, connection, sqlCondition(sql), columnIndexes);
	}

	@Override
	public PreparedStatementProxy connection_prepareStatement(FilterChain chain, ConnectionProxy connection, String sql, String[] columnNames) throws SQLException {
		return super.connection_prepareStatement(chain, connection, sqlCondition(sql), columnNames);
	}

	/**
	 * SQL 拦截器
	 *
	 * @param originalSql 原始sql
	 * @return 新的sql
	 */
	public String sqlCondition(String originalSql) {
		/**
		 * 未启用则放行
		 */
		if (!dataScopeProperties.isEnabled()) {
			return originalSql;
		}
		if (!DataScopeAuthHolder.isAuth()) {
			return originalSql;
		}
		//未取到用户则放行
		AuthUser authUser = AuthUtil.getAuthUser();
		if (authUser == null) {
			return originalSql;
		}

		/**
		 * 管理员无需数据权限过滤
		 */
		if (AuthUtil.isAdmin() || AuthUtil.isAdministrator()) {
			return originalSql;
		}
		/**
		 * 判断是否是查询语句
		 */
		if (!SELECT_PATTERN.matcher(originalSql).matches()) {
			return originalSql;
		}
		/**
		 * 获取数据权限
		 */
		DataScopeModel model = DataScopeAuthHolder.getDataScopeModel();
		if (model == null) {
			return originalSql;
		}
		DataScopeAuthHolder.setIsAuth(false);
		String condition = getSqlProcessor().sqlCondition(model, authUser, originalSql);
		DataScopeAuthHolder.setIsAuth(true);
		if (StringUtil.isBlank(condition)) {
			return originalSql;
		}
		return condition;
	}

	private static DataPermissionSqlProcessor getSqlProcessor() {
		if (sqlProcessor == null) {
			sqlProcessor = SpringUtil.getBean(DataPermissionSqlProcessor.class);
		}
		return sqlProcessor;
	}
}
